async def run_all_intake_agents(state: IntakeAgentState) -> IntakeAgentState:
    logger.info("Parallel intake agent layer (PA1–PA3) — START")
    t0 = datetime.now().timestamp()

    pa1 = ClinicalIntakeAgent(llm)
    pa2 = InsuranceIntakeAgent(llm)
    pa3 = MemoryIntakeAgent(llm)

    results = await asyncio.gather(
        pa1.run(dict(state)),
        pa2.run(dict(state)),
        pa3.run(dict(state)),
        return_exceptions=True,
    )

    agent_keys  = ["PA1", "PA2", "PA3"]
    result_keys = ["clinical_result", "insurance_result", "memory_result"]

    for i, (result, rkey, akey) in enumerate(zip(results, result_keys, agent_keys)):
        if isinstance(result, Exception):
            logger.error(f"{akey} failed: {result}")
            state["errors"].append(f"{akey}: {str(result)}")
        else:
            state[rkey] = result.get(rkey, {})
            state["agent_timings"][akey] = result.get("timing", 0)

    elapsed = round((datetime.now().timestamp() - t0) * 1000, 1)
    logger.info(f"Parallel intake agent layer — DONE ({elapsed}ms)")
