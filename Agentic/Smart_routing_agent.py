# ROBUST JSON PARSER
# Handles: markdown fences, leading text, truncated JSON
def parse_llm_json(text: str) -> Dict:
    """Robust JSON parser with aggressive recovery."""
    if not text:
        return {}
    
    text = text.strip()
    
    # Strip markdown fences and any leading/trailing text
    text = re.sub(r"```json\s*", "", text)
    text = re.sub(r"```\s*", "", text)
    
    # Try to find JSON after any explanatory text
    brace_start = text.find("{")
    if brace_start == -1:
        # Try to find any JSON-like structure
        json_match = re.search(r'\{.*\}', text, re.DOTALL)
        if json_match:
            text = json_match.group()
            brace_start = 0
        else:
            return {"raw_output": text}
    
    text = text[brace_start:]
    
    # Try direct parse first
    try:
        return json.loads(text)
    except json.JSONDecodeError as e:
        logger.debug(f"Initial JSON parse failed: {e}")
        
    # Try to repair common issues
    try:
        # Fix trailing commas
        text_fixed = re.sub(r',\s*}', '}', text)
        text_fixed = re.sub(r',\s*]', ']', text_fixed)
        return json.loads(text_fixed)
    except:
        pass
    
    # Try to extract complete JSON object by counting braces
    brace_count = 0
    in_string = False
    escape_next = False
    last_valid_pos = -1
    
    for i, char in enumerate(text):
        if escape_next:
            escape_next = False
            continue
        if char == '\\':
            escape_next = True
            continue
        if char == '"' and not escape_next:
            in_string = not in_string
            continue
        if not in_string:
            if char == '{':
                brace_count += 1
            elif char == '}':
                brace_count -= 1
                if brace_count == 0:
                    last_valid_pos = i
                    break
    
    if last_valid_pos != -1:
        candidate = text[:last_valid_pos + 1]
        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            pass
    
    # Try to repair by adding missing braces
    try:
        open_braces = text.count('{') - text.count('}')
        open_brackets = text.count('[') - text.count(']')
        open_quotes = text.count('"') % 2
        
        repaired = text
        if open_quotes == 1:
            repaired += '"'
        if open_brackets > 0:
            repaired += ']' * open_brackets
        if open_braces > 0:
            repaired += '}' * open_braces
        
        return json.loads(repaired)
    except:
        pass
    
    # Return raw output as last resort
    return {"raw_output": text[:1000] + "..." if len(text) > 1000 else text}
