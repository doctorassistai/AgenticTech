class BaseIntakeAgent:
    def __init__(self, llm_instance):
        self.llm = llm_instance

    def _elapsed(self, start: float) -> float:
        """Calculate elapsed time in milliseconds."""
        return round((datetime.now().timestamp() - start) * 1000, 1)

    async def _invoke(self, system: str, user: str, max_retries: int = 3) -> Dict:
        """Invoke LLM with automatic retry on malformed JSON."""
        last_error = None
        last_response = None
        
        for attempt in range(max_retries):
            try:
                response = await self.llm.ainvoke([
                    SystemMessage(content=system),
                    HumanMessage(content=user),
                ])
                
                last_response = response.content
                parsed = parse_llm_json(response.content)
                
                # Check if we got valid JSON with required fields
                if self._is_valid_response(parsed):
                    return parsed
                else:
                    last_error = f"Response missing required fields. Got: {list(parsed.keys()) if parsed else 'empty'}"
                    
                    # On retry, add stronger instruction based on what's missing
                    if attempt < max_retries - 1:
                        if "raw_output" in parsed:
                            user += f"\n\nYour previous response was not valid JSON. You wrote: '{parsed['raw_output'][:200]}...'\n"
                        user += "\nCRITICAL INSTRUCTION: You MUST return ONLY valid JSON. Start with '{' and end with '}'. No markdown, no code blocks, no explanatory text before or after the JSON. The entire response must be parseable by json.loads()."
                        
            except Exception as e:
                last_error = str(e)
                last_response = None
                if attempt < max_retries - 1:
                    logger.warning(f"{self.agent_id} attempt {attempt + 1} failed with exception: {last_error}. Retrying...")
                    user += "\n\nCRITICAL: Your previous response caused an error. Return ONLY valid JSON. No other text."
        
        # Return a minimal valid structure on final failure
        logger.error(f"{self.agent_id} failed after {max_retries} attempts. Last error: {last_error}")
        logger.error(f"Last response: {last_response[:500] if last_response else 'None'}")
        
        return {
            "agent": getattr(self, 'agent_id', 'unknown'),
            "patient_id": "unknown", 
            "assessment_id": "unknown",
            "error": f"Failed to generate valid JSON after {max_retries} attempts. Last error: {last_error}",
            "raw_response": last_response[:1000] if last_response else None
        }

    def _is_valid_response(self, parsed: Dict) -> bool:
        """Validate that response has expected structure."""
        if not parsed or len(parsed) == 0:
            return False
        
        # If we have raw_output only, that means parsing failed
        if "raw_output" in parsed and len(parsed) == 1:
            return False
        
        # Check for error condition
        if "error" in parsed:
            return False
        
        # For PA1 (Clinical Agent), check for required fields
        if hasattr(self, 'agent_id') and self.agent_id == "PA1":
            required_fields = ["triage", "haemodynamic_status", "neurological_assessment"]
            for field in required_fields:
                if field not in parsed:
                    logger.warning(f"PA1 missing required field: {field}")
                    return False
        
        # For PA2 (Insurance Agent), check for required fields  
        elif hasattr(self, 'agent_id') and self.agent_id == "PA2":
            required_fields = ["policy_verification", "financial_summary", "cashless_protocol"]
            for field in required_fields:
                if field not in parsed:
                    logger.warning(f"PA2 missing required field: {field}")
                    return False
        
        # For PA3 (Memory Agent), check for required fields
        elif hasattr(self, 'agent_id') and self.agent_id == "PA3":
            required_fields = ["medication_safety_review", "allergy_safety_analysis", "patient_safety_score"]
            for field in required_fields:
                if field not in parsed:
                    logger.warning(f"PA3 missing required field: {field}")
                    return False
        
        return True
