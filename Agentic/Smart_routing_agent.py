def compute_gcs(neuro: Dict):
    """Compute GCS total and classification from DB neuro record."""
    try:
        eye    = int(neuro.get("gcsEye") or 0)
        verbal = int(neuro.get("gcsVerbal") or 0)
        motor  = int(neuro.get("gcsMotor") or 0)
        total  = eye + verbal + motor
        if total == 0:
            return "Unscored", "Unscored"
        if total >= 13:
            severity = "Mild TBI / Minor impairment"
        elif total >= 9:
            severity = "Moderate TBI"
        elif total >= 3:
            severity = "Severe TBI"
        else:
            severity = "Unscored"
        return total, severity
    except Exception:
        return "Unscored", "Unscored"


