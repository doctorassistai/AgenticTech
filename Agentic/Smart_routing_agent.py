async def fetch_latest_intake(patient_id: str, assessment_id: Optional[str] = None) -> Dict:
    try:
        query = {"patient_id": patient_id}
        if assessment_id:
            query["assessment_id"] = assessment_id
        cursor = intake_collection.find(query, {"_id": 0}).sort("created_at", -1).limit(1)
        records = await cursor.to_list(length=1)
        return records[0] if records else {}
    except Exception as e:
        logger.error(f"Intake fetch failed for {patient_id}: {e}")
        return {}


