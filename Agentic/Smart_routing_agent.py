def compute_shock_index(vitals: Dict) -> tuple:
    """Compute Shock Index = HR / SBP from DB vitals."""
    try:
        hr  = float(vitals.get("heartRate") or 0)
        sbp = float(vitals.get("systolicBP") or 1)
        if sbp == 0:
            return "N/A", "Unable to compute (SBP=0)"
        si = round(hr / sbp, 2)
        if si < 0.9:
            interp = "Normal (<0.9) — haemodynamically stable"
        elif si <= 1.0:
            interp = "Borderline (0.9–1.0) — early shock risk"
        elif si <= 1.4:
            interp = "Class II shock (1.0–1.4) — significant haemorrhage"
        else:
            interp = "Severe shock / exsanguination risk (>1.4)"
        return si, interp
    except Exception:
        return "N/A", "Unable to compute"


def compute_map(vitals: Dict) -> tuple:
    """Compute Mean Arterial Pressure from DB vitals."""
    try:
        sbp = float(vitals.get("systolicBP") or 0)
        dbp = float(vitals.get("diastolicBP") or 0)
        if sbp == 0 and dbp == 0:
            return "N/A", "Unable to compute"
        map_val = round(dbp + (sbp - dbp) / 3, 1)
        interp = (
            "Adequate cerebral perfusion (MAP ≥70 mmHg)"
            if map_val >= 70
            else f"Insufficient cerebral perfusion — CRITICAL (MAP={map_val} <70 mmHg)"
        )
        return map_val, interp
    except Exception:
        return "N/A", "Unable to compute"


def compute_last_dose_timing(last_dose_str: str) -> tuple:
    """
    Compute hours since last medication dose.
    Returns (hours_since_str, timing_note).
    Fully dynamic — works for any last-dose timestamp from DB.
    """
    if not last_dose_str or last_dose_str in ("Not recorded", "Unknown", ""):
        return "Unknown", "Last dose timing not recorded — cannot assess pharmacological activity"
    try:
        last_dose_dt = datetime.fromisoformat(str(last_dose_str))
        now = datetime.now()
        hours_since = round((now - last_dose_dt).total_seconds() / 3600, 1)
        return str(hours_since), f"Approximately {hours_since} hours since last recorded dose"
    except Exception:
        return "Unknown", f"Could not parse last dose timestamp: {last_dose_str}"


