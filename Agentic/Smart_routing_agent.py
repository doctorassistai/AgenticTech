def sv(value, default: str = "Not recorded") -> str:
    """Return string value or default if None/empty."""
    if value is None:
        return default
    s = str(value).strip()
    return s if s else default


def si_num(value, default=0):
    """Return numeric value safely."""
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


