async def run_intake_pipeline(
    patient_id: str,
    assessment_id: Optional[str] = None
) -> IntakeAgentState:

    intake_record, patient_record = await asyncio.gather(
        fetch_latest_intake(patient_id, assessment_id),
        fetch_patient_base(patient_id),
    )

    if not intake_record:
        raise HTTPException(
            status_code=404,
            detail=f"No intake assessment found for patient_id: {patient_id}"
        )

    resolved_assessment_id = intake_record.get("assessment_id", str(uuid.uuid4()))

    state: IntakeAgentState = {
        "patient_id":       patient_id,
        "assessment_id":    resolved_assessment_id,
        "intake_record":    intake_record,
        "patient_record":   patient_record,
        "clinical_result":  None,
        "insurance_result": None,
        "memory_result":    None,
        "synthesis_result": None,
        "errors":           [],
        "agent_timings":    {},
    }

    state = await run_all_intake_agents(state)

    synthesis_agent = IntakeSynthesisAgent(llm_synthesis)
    state = await synthesis_agent.run(state)

    return state


